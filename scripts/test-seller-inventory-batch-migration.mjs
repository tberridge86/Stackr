async function authenticate(client, userId, { entitlement = true, userMetadataEntitlement } = {}) {
  await client.query('set role authenticated');
  await client.query("select set_config('request.jwt.claim.sub', $1, false)", [userId]);
  await client.query("select set_config('request.jwt.claims', $1, false)", [JSON.stringify({
    sub: userId,
    role: 'authenticated',
    app_metadata: entitlement === undefined ? {} : { stackr_premium_seller: entitlement },
    user_metadata: userMetadataEntitlement === undefined
      ? {}
      : { stackr_premium_seller: userMetadataEntitlement },
  })]);
}

async function callBatch(client, input) {
  const identityResult = await client.query(
    "select nullif(current_setting('request.jwt.claim.sub', true), '') as user_id",
  );
  const requestUserId = identityResult.rows[0]?.user_id ?? userOne;
  const requestId = input.rawRequestId
    ? input.requestId
    : `seller-batch:${requestUserId}:${input.requestId}`;
  const result = await client.query(
    `select public.commit_seller_inventory_batch(
      $1::text,
      $2::jsonb,
      $3::jsonb,
      $4::jsonb,
      $5::jsonb,
      $6::jsonb
    ) as result`,
    [
      requestId,
      JSON.stringify(input.expectedInventory),
      JSON.stringify(input.inventory),
      JSON.stringify(input.movements ?? []),
      input.sale == null ? null : JSON.stringify(input.sale),
      JSON.stringify(input.binderDeltas ?? []),
    ],
  );
  return result.rows[0].result;
}

async function inspectCounts(client) {
  await client.query('reset role');
  const result = await client.query(`
    select
      (select count(*)::int from public.seller_inventory_items) as inventory_count,
      (select coalesce(max(quantity), 0)::int from public.seller_inventory_items) as inventory_quantity,
      (select count(*)::int from public.inventory_movements) as movement_count,
      (select count(*)::int from public.seller_sale_transactions) as sale_count,
      (select count(*)::int from public.seller_sale_transaction_items) as sale_line_count,
      (select count(*)::int from private.seller_inventory_batch_commits) as commit_count,
      (select coalesce(max(case when owned then owned_quantity else 0 end), 0)::int from public.binder_cards) as binder_quantity
  `);
  return result.rows[0];
}


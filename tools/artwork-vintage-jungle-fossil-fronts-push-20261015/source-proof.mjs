export function validateActual(actual, known) {
  check(canonicalHash(actual) === known.actual, 'Accepted whole-front actual signature changed');
  check(actual.category === known.category && actual.language === 'ja' && actual.nativeTitle && actual.printedSetMark, 'Positive actual Japanese category/title/set mark required');
  check(actual.printedCollectorNumber === null && actual.canonicalAliasNotPrintedCollector === true, 'Internal alias must not become printed collector number');
  if (known.category === 'Pokemon') {
    check(Number.isInteger(actual.printedNationalDex) && actual.printedNationalDex > 0 && actual.printedNumberIsNationalDex === true, 'Actual printed NationalDex required for these90 Pokemon');
    check(Number.isInteger(actual.hp) && actual.hp > 0 && actual.stage && actual.retreatCost !== undefined, 'Full Pokemon body/HP/stage/retreat required');
    const ditto = known.setCode === 'PMCG3' && known.alias === '042' && actual.printedNationalDex === 132;
    check(Array.isArray(actual.orderedAttacks) && (ditto ? actual.orderedAttacks.length === 0 && actual.abilities?.length === 1 && actual.abilities[0].name === 'へんしん' : actual.orderedAttacks.length > 0), 'Exact ordered attacks or Ditto transformation power required');
  } else {
    check(known.category === 'Trainer' && (actual.header ?? actual.printedHeader) === 'TRAINER', 'Actual Trainer header required');
    check(actual.printedNationalDex === null && actual.printedNumberIsNationalDex === false && actual.stage === null && actual.retreatCost === null, 'Trainer must not borrow Pokemon/Dex fields');
    check((actual.orderedAttacks ?? actual.pokemonAttacks).length === 0 && (actual.abilities ?? actual.pokemonAbilities).length === 0, 'Trainer cannot borrow attacks or abilities');
    check(actual.nativeRules?.length > 0 && actual.sourceBodyAbsent === true && actual.sourceBodySemanticsReviewed === false, 'Actual Trainer rules and absent-provider qualification required');
    if (known.setCode === 'PMCG3' && known.alias === '046') {
      check(actual.hp === 10 && actual.specialTrainerProperties?.printedHPActuallyPresent === true && actual.specialTrainerProperties?.mayBePlayedAsPokemon === true && actual.specialTrainerProperties?.unevolvedKnockoutDoesNotCountAsKnockout === true, 'Mysterious Fossil actual HP10/special play rules required');
    } else check(actual.hp === null, 'Only exact Mysterious Fossil has printed Trainer HP');
    check(known.actual !== known.historicalActual, 'New Trainer qualification must retain distinct historical signature');
  }
}

